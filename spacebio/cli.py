"""Spaceflight Biology Navigator command-line utilities (no external Python dependencies)."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import time
from datetime import datetime, timezone
import os

from .literature import make_query, search_pubmed
from .osdr import ALL_DATASET_METADATA_URL, DATASETS_URL, catalog_snapshot, read_remote_json
from .quality import validate_seed
from .site import build_catalog_js, build_gap_hypotheses_js, build_seed_js

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / 'data' / 'seed' / 'brain_pilot.json'
JS = ROOT / 'web' / 'data' / 'seed.js'
GAP_SEED = ROOT / 'data' / 'seed' / 'cross_topic_gap_hypotheses.json'
GAP_JS = ROOT / 'web' / 'data' / 'gap-hypotheses.js'


def write_json(path: Path, data: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')


def write_json_atomic(path: Path, data: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.tmp')
    temporary.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    temporary.replace(path)


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def display_path(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description='Spaceflight Biology Navigator research metadata tools')
    commands = parser.add_subparsers(dest='command', required=True)
    validate = commands.add_parser('validate', help='Validate seed graph structure')
    validate.add_argument('--seed', type=Path, default=SEED, help='Seed JSON to validate')
    build = commands.add_parser('build', help='Generate browser data from JSON seed')
    build.add_argument('--seed', type=Path, default=SEED, help='Seed JSON to build')
    build.add_argument('--out', type=Path, default=JS, help='Generated browser JavaScript path')
    build.add_argument('--check', action='store_true', help='Exit nonzero if browser data is stale')
    build_gaps = commands.add_parser('build-gaps', help='Generate browser data from cross-topic gap-hypothesis JSON')
    build_gaps.add_argument('--seed', type=Path, default=GAP_SEED, help='Gap-hypothesis JSON to build')
    build_gaps.add_argument('--out', type=Path, default=GAP_JS, help='Generated browser JavaScript path')
    build_gaps.add_argument('--check', action='store_true', help='Exit nonzero if browser data is stale')
    catalog = commands.add_parser('catalog', help='Fetch the full Biological Data API dataset index and aggregate metadata')
    catalog.add_argument('--fixture', type=Path, help='Offline dataset-index JSON fixture rather than remote request')
    catalog.add_argument('--metadata-fixture', type=Path, help='Offline wildcard metadata JSON fixture')
    catalog.add_argument('--source', help='Source URL label to store in the snapshot')
    catalog.add_argument('--out', type=Path, default=ROOT / 'data/catalog/osdr_biodata_snapshot.json')
    catalog.add_argument('--site-out', type=Path, help='Also generate static browser catalog data at this path')
    pubmed = commands.add_parser('pubmed', help='Find candidate PubMed articles mentioning OSD accession')
    pubmed.add_argument('accession', help='OSD-NNN')
    pubmed.add_argument('--out', type=Path, help='Write JSON to file; otherwise stdout')
    pubmed.add_argument('--email', help='Contact email for NCBI; defaults to SPACEFLIGHT_BIOLOGY_NCBI_EMAIL')
    batch = commands.add_parser('pubmed-batch', help='Search PubMed for accessions in a catalog snapshot; hits remain unverified')
    batch.add_argument('--catalog', type=Path, default=ROOT / 'data/catalog/osdr_biodata_snapshot.json')
    batch.add_argument('--out', type=Path, default=ROOT / 'data/generated/pubmed_candidates.json')
    batch.add_argument('--max-requests', type=int, default=100, help='Maximum new accession searches per run (default: 100)')
    batch.add_argument('--delay', type=float, default=0.4, help='Seconds between requests; minimum is 0.34 to respect NCBI rate guidance')
    batch.add_argument('--retmax', type=int, default=100, help='Maximum candidate PMIDs returned per accession (1-1000)')
    batch.add_argument('--email', help='Contact email for NCBI; defaults to SPACEFLIGHT_BIOLOGY_NCBI_EMAIL')
    args = parser.parse_args(argv)
    try:
        if args.command == 'build-gaps':
            seed = json.loads(args.seed.read_text(encoding='utf-8'))
            if not isinstance(seed, dict) or not isinstance(seed.get('hypotheses'), list):
                raise ValueError(f'Gap-hypothesis source at {args.seed} must contain a hypotheses list')
            desired = '/* Generated by python -m spacebio.cli build-gaps. Do not edit. */\nwindow.SPACEBIO_GAP_HYPOTHESES = ' + json.dumps(seed, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c').replace('>', '\\u003e') + ';\n'
            if args.check:
                if not args.out.exists() or args.out.read_text(encoding='utf-8') != desired:
                    print(f'{display_path(args.out)} is out of date; rerun python -m spacebio.cli build-gaps', file=sys.stderr)
                    return 1
                print(f'Gap-hypothesis browser data is current at {display_path(args.out)}.')
            else:
                build_gap_hypotheses_js(args.seed, args.out)
                print(f'Wrote {display_path(args.out)}')
            return 0
        if args.command in {'validate', 'build'}:
            seed_path = args.seed
            seed = json.loads(seed_path.read_text(encoding='utf-8'))
            errors = validate_seed(seed)
            if errors:
                print('\n'.join(errors), file=sys.stderr)
                return 1
            if args.command == 'validate':
                print(f'Graph integrity OK: {len(seed["papers"])} papers, {len(seed["datasets"])} datasets in {display_path(seed_path)}.')
                return 0
            desired = '/* Generated by python -m spacebio.cli build. Do not edit. */\nwindow.SPACEBIO_SEED = ' + json.dumps(seed, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c').replace('>', '\\u003e') + ';\n'
            if args.check:
                if not args.out.exists() or args.out.read_text(encoding='utf-8') != desired:
                    print(f'{display_path(args.out)} is out of date; rerun python -m spacebio.cli build --seed {display_path(seed_path)} --out {display_path(args.out)}', file=sys.stderr)
                    return 1
                print(f'Browser seed is current at {display_path(args.out)}.')
            else:
                build_seed_js(seed_path, args.out)
                print(f'Wrote {display_path(args.out)}')
            return 0
        if args.command == 'catalog':
            if args.fixture:
                index = json.loads(args.fixture.read_text(encoding='utf-8'))
                metadata = (json.loads(args.metadata_fixture.read_text(encoding='utf-8'))
                            if args.metadata_fixture else {})
                raw = {'dataset_index': index, 'dataset_metadata': metadata}
                source_url = args.source or str(args.fixture)
            else:
                if args.metadata_fixture:
                    raise ValueError('--metadata-fixture requires --fixture')
                index = read_remote_json(DATASETS_URL)
                metadata = read_remote_json(ALL_DATASET_METADATA_URL, timeout=120)
                raw = {'dataset_index': index, 'dataset_metadata': metadata}
                source_url = args.source or DATASETS_URL
            snap = catalog_snapshot(raw, source_url)
            if not snap['datasets']:
                raise ValueError('No OSD accessions were found in the catalogue response; no snapshot was written.')
            write_json(args.out, snap)
            if args.site_out:
                build_catalog_js(args.out, args.site_out)
            print(f'Found {snap["total_ids_found"]} OSD accessions, saved snapshot to {args.out}.')
            if args.site_out:
                print(f'Wrote static browser catalog to {args.site_out}.')
            return 0
        if args.command == 'pubmed':
            result = search_pubmed(args.accession, email=args.email)
            if args.out:
                write_json(args.out, result)
                print(f'Saved {len(result["candidate_pmids"])} UNVERIFIED hits to {args.out}.')
            else:
                print(json.dumps(result, indent=2))
            return 0
        if args.command == 'pubmed-batch':
            if args.max_requests < 1:
                raise ValueError('--max-requests must be at least 1')
            if args.max_requests > 100:
                raise ValueError('--max-requests cannot exceed 100 per run; run larger batches during NCBI off-peak hours')
            if args.delay < 0.34:
                raise ValueError('--delay must be at least 0.34 seconds to respect NCBI rate guidance')
            if not 1 <= args.retmax <= 1000:
                raise ValueError('--retmax must be between 1 and 1000')
            source_catalog = json.loads(args.catalog.read_text(encoding='utf-8'))
            if not isinstance(source_catalog, dict):
                raise ValueError(f'Catalog at {args.catalog} must be a JSON object')
            accessions = source_catalog.get('accessions')
            if accessions is None:
                dataset_records = source_catalog.get('datasets', [])
                if not isinstance(dataset_records, list):
                    raise ValueError(f'Catalog at {args.catalog} must contain an accessions or datasets list')
                if any(not isinstance(item, dict) for item in dataset_records):
                    raise ValueError(f'Catalog at {args.catalog} contains a non-object dataset record')
                accessions = [item.get('accession') for item in dataset_records]
            if not isinstance(accessions, list):
                raise ValueError(f'Catalog at {args.catalog} must contain an accessions list')
            accessions = list(dict.fromkeys(str(value).upper() for value in accessions if value))
            if not accessions:
                raise ValueError(f'No OSD accessions found in {args.catalog}')
            for accession in accessions:
                make_query(accession)
            state = json.loads(args.out.read_text(encoding='utf-8')) if args.out.exists() else {}
            if not isinstance(state, dict):
                raise ValueError(f'Existing output at {args.out} must be a JSON object')
            results = state.get('results', {})
            errors = state.get('errors', {})
            if not isinstance(results, dict) or not isinstance(errors, dict):
                raise ValueError(f'Existing output at {args.out} has an invalid results/errors shape')
            results = {key: value for key, value in results.items() if key in accessions and isinstance(value, dict)}
            errors = {key: value for key, value in errors.items() if key in accessions}
            queued = [accession for accession in accessions if not isinstance(results.get(accession), dict) or results[accession].get('status') != 'UNVERIFIED_CANDIDATES']
            attempted = 0
            contact_email = args.email or os.environ.get('SPACEFLIGHT_BIOLOGY_NCBI_EMAIL')
            for accession in queued[:args.max_requests]:
                try:
                    results[accession] = search_pubmed(
                        accession, retmax=args.retmax, email=contact_email)
                    results[accession]['retrieved_utc'] = utc_now()
                    errors.pop(accession, None)
                    print(f'{accession}: {results[accession]["count_reported"]} candidate hits (unverified)')
                except (OSError, ValueError, KeyError) as exc:
                    message = str(exc)
                    if contact_email:
                        message = message.replace(contact_email, '[redacted]')
                    errors[accession] = {'error_type': type(exc).__name__, 'message': message[:300]}
                    print(f'{accession}: request failed ({type(exc).__name__})', file=sys.stderr)
                attempted += 1
                remaining = [item for item in accessions if not isinstance(results.get(item), dict) or results[item].get('status') != 'UNVERIFIED_CANDIDATES']
                state = {
                    'schema_version': 1,
                    'source_catalog': str(args.catalog),
                    'catalog_source_url': source_catalog.get('source_url'),
                    'catalog_retrieved_utc': source_catalog.get('retrieved_utc'),
                    'catalog_payload_sha256': source_catalog.get('source_payload_sha256'),
                    'updated_utc': utc_now(),
                    'attempts_this_run': attempted,
                    'status': 'COMPLETE' if not remaining else 'IN_PROGRESS',
                    'total_accessions': len(accessions),
                    'completed_accessions': len(accessions) - len(remaining),
                    'remaining_accessions': remaining,
                    'results': results,
                    'errors': errors,
                    'warning': 'PubMed hits are unverified candidates; inspect the publication and dataset metadata before creating a relationship.',
                }
                write_json_atomic(args.out, state)
                if attempted < min(len(queued), args.max_requests):
                    time.sleep(args.delay)
            if attempted == 0:
                state = {
                    'schema_version': 1,
                    'source_catalog': str(args.catalog),
                    'catalog_source_url': source_catalog.get('source_url'),
                    'catalog_retrieved_utc': source_catalog.get('retrieved_utc'),
                    'catalog_payload_sha256': source_catalog.get('source_payload_sha256'),
                    'updated_utc': utc_now(),
                    'attempts_this_run': attempted,
                    'status': 'COMPLETE',
                    'total_accessions': len(accessions),
                    'completed_accessions': len(accessions),
                    'remaining_accessions': [],
                    'results': results,
                    'errors': errors,
                    'warning': 'PubMed hits are unverified candidates; inspect the publication and dataset metadata before creating a relationship.',
                }
                write_json_atomic(args.out, state)
            if not contact_email:
                print('Note: set SPACEFLIGHT_BIOLOGY_NCBI_EMAIL or pass --email for NCBI contact metadata.', file=sys.stderr)
            print(f'Processed {attempted} searches; {len(state["remaining_accessions"])} remain. Saved resumable results to {args.out}.')
            return 0
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as exc:
        print(f'{args.command}: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())






