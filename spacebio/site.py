"""Make a self-contained seed JavaScript file from the editable JSON data."""
from __future__ import annotations

import json
from pathlib import Path

from .osdr import redact_public_emails


def build_seed_js(source: Path, destination: Path) -> str:
    data = json.loads(source.read_text(encoding='utf-8'))
    # Avoid injection of HTML script delimiters through source text.
    serialized = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    serialized = serialized.replace('<', '\\u003c').replace('>', '\\u003e')
    output = '/* Generated by python -m spacebio.cli build. Do not edit. */\nwindow.SPACEBIO_SEED = ' + serialized + ';\n'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(output, encoding='utf-8')
    return output


def build_catalog_js(source: Path, destination: Path) -> str:
    """Build the static catalogue page data from a saved API snapshot."""
    data = redact_public_emails(json.loads(source.read_text(encoding='utf-8')))
    datasets = data.get('datasets')
    if datasets is None:
        datasets = [
            {
                'accession': accession,
                'api_url': f'https://visualization.osdr.nasa.gov/biodata/api/v2/dataset/{accession}/',
                'record_url': f'https://osdr.nasa.gov/bio/repo/data/studies/{accession}',
            }
            for accession in data.get('accessions', [])
        ]
    catalog = {
        'schema_version': data.get('schema_version', 1),
        'source_url': data.get('source_url', ''),
        'metadata_source_url': data.get('metadata_source_url', ''),
        'retrieved_utc': data.get('retrieved_utc'),
        'source_payload_sha256': data.get('source_payload_sha256', ''),
        'total_ids_found': data.get('total_ids_found', len(datasets)),
        'metadata_record_count': data.get('metadata_record_count', 0),
        'publication_title_count': data.get('publication_title_count', 0),
        'datasets': datasets,
        'topics': data.get('topics', []),
        'topic_note': data.get('topic_note', ''),
        'coverage_note': data.get('coverage_note', ''),
    }
    serialized = json.dumps(catalog, ensure_ascii=False, separators=(',', ':'))
    serialized = serialized.replace('<', '\\u003c').replace('>', '\\u003e')
    output = '/* Generated by python -m spacebio.cli catalog --site-out. Do not edit. */\nwindow.SPACEBIO_CATALOG = ' + serialized + ';\n'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(output, encoding='utf-8')
    return output

